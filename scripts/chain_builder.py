#!/usr/bin/env python3
"""
chain_builder.py - Standalone server and CLI for the Visual Chain Builder.

Usage:
    ./scripts/chain_builder.py [path/to/chain.toml] [--port 8095] [--handler-dir <path>]
"""

import argparse
import http.server
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import threading
from typing import Any, Optional

# Ensure scripts root is in sys.path
scripts_dir = Path(__file__).resolve().parent
if str(scripts_dir) not in sys.path:
    sys.path.insert(0, str(scripts_dir))

from proxy_runner.config import load_chain_config
from proxy_runner.schema_validator import (
    discover_handler_schemas,
    validate_chain_topology,
)


class ChainBuilderHTTPHandler(http.server.SimpleHTTPRequestHandler):
    schemas: dict[str, Any] = {}
    current_chain: dict[str, Any] = {}
    current_file_path: Optional[Path] = None
    root_dir: Path = Path(__file__).resolve().parent.parent

    def _send_json(self, status_code: int, payload: dict | list):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status_code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
        self.end_headers()
        self.wfile.write(body)

    def _read_json_body(self) -> dict:
        content_len = int(self.headers.get("Content-Length", 0))
        if content_len <= 0:
            return {}
        raw = self.rfile.read(content_len)
        try:
            return json.loads(raw.decode("utf-8"))
        except Exception:
            return {}

    def do_GET(self):
        builder_dir = self.root_dir / "scripts" / "builder"

        if self.path in ("/", "/index.html"):
            index_file = builder_dir / "index.html"
            if index_file.is_file():
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
                self.end_headers()
                self.wfile.write(index_file.read_bytes())
                return

        elif self.path.startswith(("/css/", "/js/", "/vendor/")):
            clean_path = self.path.split("?")[0].lstrip("/")
            static_file = builder_dir / clean_path
            if static_file.is_file():
                content_type = "text/plain"
                if clean_path.endswith(".css"):
                    content_type = "text/css"
                elif clean_path.endswith(".js"):
                    content_type = "application/javascript"
                self.send_response(200)
                self.send_header("Content-Type", content_type)
                self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
                self.end_headers()
                self.wfile.write(static_file.read_bytes())
                return

        elif self.path == "/api/schemas":
            # Refresh schemas dynamically
            self.__class__.schemas = discover_handler_schemas()
            self._send_json(200, self.schemas)
            return

        elif self.path == "/api/metadata":
            from proxy_runner.metadata import get_metadata_catalog_definitions
            self._send_json(200, get_metadata_catalog_definitions())
            return

        elif self.path.startswith("/api/payload_contract"):
            from urllib.parse import parse_qs, urlparse
            from proxy_runner.payload_contracts import inspect_payload_contract
            query = parse_qs(urlparse(self.path).query)
            fmt = query.get("format", [""])[0]
            file_path = query.get("file", [""])[0]
            resolved = (self.root_dir / file_path).resolve()
            self._send_json(200, inspect_payload_contract(fmt, resolved))
            return

        elif self.path == "/api/chain":
            self._send_json(200, self.current_chain)
            return

        self.send_response(404)
        self.end_headers()

    def do_POST(self):
        if self.path == "/api/chain/validate":
            payload = self._read_json_body()
            res = validate_chain_topology(payload, self.schemas)
            self._send_json(200, res)
            return

        elif self.path == "/api/chain/save":
            payload = self._read_json_body()
            target_path = self.current_file_path or (self.root_dir / "chains" / payload.get("filename", "custom_chain.toml"))
            target_path.parent.mkdir(parents=True, exist_ok=True)

            toml_lines = [
                f'# Auto-generated by Proxy Visual Chain Builder',
            ]
            if payload.get("name"):
                toml_lines.append(f'# Pipeline Name: {payload.get("name")}')
            toml_lines.extend([
                f'backend = "{payload.get("backend", "file")}"',
                "",
                "[config]",
            ])
            for k, v in payload.get("config", {}).items():
                if isinstance(v, bool):
                    toml_lines.append(f'"{k}" = {str(v).lower()}')
                elif isinstance(v, (int, float)):
                    toml_lines.append(f'"{k}" = {v}')
                else:
                    toml_lines.append(f'"{k}" = "{v}"')

            for h in payload.get("handlers", []):
                toml_lines.append("")
                toml_lines.append("[[handlers]]")
                toml_lines.append(f'name = "{h.get("name", "handler")}"')
                toml_lines.append(f'type = "{h.get("type", "")}"')
                if "input_channel" in h:
                    toml_lines.append(f'input_channel = "{h["input_channel"]}"')
                if "input_channels" in h:
                    toml_lines.append(f'input_channels = "{h["input_channels"]}"')
                if "output_channel" in h:
                    toml_lines.append(f'output_channel = "{h["output_channel"]}"')
                if "output_channels" in h:
                    toml_lines.append(f'output_channels = "{h["output_channels"]}"')

                h_cfg = h.get("config", {})
                if h_cfg:
                    toml_lines.append("[handlers.config]")
                    for ck, cv in h_cfg.items():
                        if isinstance(cv, bool):
                            toml_lines.append(f'"{ck}" = {str(cv).lower()}')
                        elif isinstance(cv, (int, float)):
                            toml_lines.append(f'"{ck}" = {cv}')
                        else:
                            toml_lines.append(f'"{ck}" = "{cv}"')

            toml_lines.append("")
            target_path.write_text("\n".join(toml_lines), encoding="utf-8")
            self._send_json(200, {"status": "ok", "path": str(target_path)})
            return

        elif self.path == "/api/chain/run":
            payload = self._read_json_body()
            # Save chain to temp file and launch chain_runner.py with sim backend
            tmp_chain = Path(tempfile.mktemp(prefix="builder_chain_", suffix=".toml"))
            
            # Clone chain and set backend to sim for visual execution
            payload_sim = dict(payload)
            payload_sim["backend"] = "sim"
            
            toml_lines = [
                'backend = "sim"',
                "",
                "[config]",
            ]
            for k, v in payload_sim.get("config", {}).items():
                toml_lines.append(f'"{k}" = "{v}"')

            for h in payload_sim.get("handlers", []):
                toml_lines.append("")
                toml_lines.append("[[handlers]]")
                toml_lines.append(f'name = "{h.get("name")}"')
                toml_lines.append(f'type = "{h.get("type")}"')
                if "input_channel" in h:
                    toml_lines.append(f'input_channel = "{h["input_channel"]}"')
                if "input_channels" in h:
                    toml_lines.append(f'input_channels = "{h["input_channels"]}"')
                if "output_channel" in h:
                    toml_lines.append(f'output_channel = "{h["output_channel"]}"')
                if "output_channels" in h:
                    toml_lines.append(f'output_channels = "{h["output_channels"]}"')
                h_cfg = h.get("config", {})
                if h_cfg:
                    toml_lines.append("[handlers.config]")
                    for ck, cv in h_cfg.items():
                        toml_lines.append(f'"{ck}" = "{cv}"')
            toml_lines.append("")
            tmp_chain.write_text("\n".join(toml_lines), encoding="utf-8")

            # Launch chain_runner.py in background
            runner_script = self.root_dir / "scripts" / "chain_runner.py"
            subprocess.Popen([sys.executable, str(runner_script), str(tmp_chain)])
            self._send_json(200, {"status": "ok", "url": "http://localhost:8090"})
            return

        self.send_response(404)
        self.end_headers()

    def log_message(self, format, *args):
        pass


def main() -> int:
    parser = argparse.ArgumentParser(description="Proxy Visual Chain Builder Studio")
    parser.add_argument("chain", nargs="?", help="Optional path to existing TOML/JSON chain file")
    parser.add_argument("--port", type=int, default=8095, help="HTTP server port (default: 8095)")
    parser.add_argument("--handler-dir", action="append", help="Extra directory to scan for handler schemas")
    args = parser.parse_args()

    extra_paths = [Path(p) for p in args.handler_dir] if args.handler_dir else []
    schemas = discover_handler_schemas(extra_paths)
    print(f"[ChainBuilder] Discovered {len(schemas)} handler schemas:")
    for name, s in sorted(schemas.items()):
        print(f"  • {name} ({s.get('displayName', name)}) [{s.get('role', 'processor')}]")

    initial_chain = {}
    chain_file_path = None
    if args.chain:
        chain_file_path = Path(args.chain).resolve()
        if chain_file_path.is_file():
            print(f"[ChainBuilder] Loading initial chain: {chain_file_path}")
            initial_chain = load_chain_config(chain_file_path)

    ChainBuilderHTTPHandler.schemas = schemas
    ChainBuilderHTTPHandler.current_chain = initial_chain
    ChainBuilderHTTPHandler.current_file_path = chain_file_path

    server = http.server.HTTPServer(("0.0.0.0", args.port), ChainBuilderHTTPHandler)
    url = f"http://localhost:{args.port}"
    print(f"\n=======================================================")
    print(f"  Proxy Visual Chain Builder is live at: {url}")
    print(f"=======================================================\n")

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n[ChainBuilder] Shutting down.")
        server.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(main())

