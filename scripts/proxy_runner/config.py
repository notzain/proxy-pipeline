"""
Chain and handler configuration management and binary discovery.
"""

import json
from pathlib import Path
from typing import Any

try:
    import tomllib
except ModuleNotFoundError:
    try:
        import tomli as tomllib
    except ModuleNotFoundError:
        import toml as tomllib


def load_chain_config(config_path: Path) -> dict[str, Any]:
    if not config_path.is_file():
        raise FileNotFoundError(f"Configuration file not found: {config_path}")

    content = config_path.read_text(encoding="utf-8")
    if config_path.suffix.lower() == ".json":
        return json.loads(content)
    elif config_path.suffix.lower() == ".toml":
        if tomllib is None:
            raise RuntimeError("Python 3.11+ is required for built-in TOML support.")
        return tomllib.loads(content)
    else:
        if tomllib:
            try:
                return tomllib.loads(content)
            except Exception:
                pass
        return json.loads(content)


def serialize_chain_to_toml(chain_dict: dict[str, Any], backend_override: str | None = None) -> str:
    """
    Serializes a chain definition dictionary to a valid TOML document,
    supporting nested arrays of tables ([[handlers.config.rules]]),
    multiline string values, and escaped strings.
    """
    backend = backend_override if backend_override else chain_dict.get("backend", "file")
    lines: list[str] = ["# Auto-generated by Proxy Visual Chain Builder"]
    p_name = chain_dict.get("name")
    if p_name:
        lines.append(f"# Pipeline Name: {p_name}")
    lines.append(f'backend = "{backend}"\n\n[config]')

    for k, v in chain_dict.get("config", {}).items():
        if isinstance(v, bool):
            lines.append(f'"{k}" = {str(v).lower()}')
        elif isinstance(v, (int, float)):
            lines.append(f'"{k}" = {v}')
        else:
            lines.append(f'"{k}" = {json.dumps(str(v))}')

    for h in chain_dict.get("handlers", []):
        lines.append("")
        lines.append("[[handlers]]")
        lines.append(f'name = {json.dumps(h.get("name", "handler"))}')
        lines.append(f'type = {json.dumps(h.get("type", ""))}')
        if "input_channel" in h and h["input_channel"]:
            lines.append(f'input_channel = {json.dumps(str(h["input_channel"]))}')
        if "input_channels" in h and h["input_channels"]:
            in_ch = h["input_channels"]
            in_ch_str = ",".join(str(c) for c in in_ch) if isinstance(in_ch, list) else str(in_ch)
            lines.append(f'input_channels = {json.dumps(in_ch_str)}')
        if "output_channel" in h and h["output_channel"]:
            lines.append(f'output_channel = {json.dumps(str(h["output_channel"]))}')
        if "output_channels" in h and h["output_channels"]:
            out_ch = h["output_channels"]
            out_ch_str = ",".join(str(c) for c in out_ch) if isinstance(out_ch, list) else str(out_ch)
            lines.append(f'output_channels = {json.dumps(out_ch_str)}')

        h_cfg = h.get("config", {})
        if h_cfg:
            lines.append("[handlers.config]")
            complex_arrays: list[tuple[str, list[Any]]] = []
            for ck, cv in h_cfg.items():
                if isinstance(cv, list):
                    complex_arrays.append((ck, cv))
                elif isinstance(cv, dict):
                    lines.append(f'"{ck}" = {json.dumps(cv)}')
                elif isinstance(cv, bool):
                    lines.append(f'"{ck}" = {str(cv).lower()}')
                elif isinstance(cv, (int, float)):
                    lines.append(f'"{ck}" = {cv}')
                else:
                    lines.append(f'"{ck}" = {json.dumps(str(cv))}')

            for arr_key, arr_items in complex_arrays:
                for item in arr_items:
                    lines.append(f"\n[[handlers.config.{arr_key}]]")
                    if isinstance(item, dict):
                        for item_key, item_val in item.items():
                            if item_val is None:
                                continue
                            if isinstance(item_val, bool):
                                lines.append(f"{item_key} = {str(item_val).lower()}")
                            elif isinstance(item_val, (int, float)):
                                lines.append(f"{item_key} = {item_val}")
                            elif isinstance(item_val, (dict, list)):
                                lines.append(f"{item_key} = {json.dumps(item_val)}")
                            else:
                                lines.append(f"{item_key} = {json.dumps(str(item_val))}")

    lines.append("")
    return "\n".join(lines)


def find_bin_dir(root_dir: Path, requested_bin_dir: str | None = None) -> Path:
    if requested_bin_dir:
        candidate = Path(requested_bin_dir)
        if candidate.is_dir():
            return candidate

    search_paths = [
        root_dir / "build" / "bin",
        root_dir / "build" / "gcc16-release" / "bin",
        root_dir / "build" / "gcc16-debug" / "bin",
        root_dir / "build" / "release" / "bin",
        root_dir / "build" / "debug" / "bin",
        root_dir / "bin",
    ]
    for p in search_paths:
        if p.is_dir():
            return p

    raise FileNotFoundError(
        f"Could not find build bin directory. Looked in: {[str(p) for p in search_paths]}. "
        "Please build the project first or provide --bin-dir."
    )


def flatten_dict(d: dict[str, Any], prefix: str = "") -> list[tuple[str, Any]]:
    items: list[tuple[str, Any]] = []
    for k, v in d.items():
        full_key = f"{prefix}.{k}" if prefix else str(k)
        if isinstance(v, dict):
            items.extend(flatten_dict(v, full_key))
        else:
            items.append((full_key, v))
    return items


def generate_handler_config(
    global_config: dict[str, Any],
    backend_name: str,
    handler_spec: dict[str, Any],
) -> str:
    """Generate a structured JSON configuration for a handler instance."""
    result: dict[str, Any] = {}

    def _set_path(target: dict[str, Any], path: str, val: Any) -> None:
        parts = path.split(".")
        curr = target
        for p in parts[:-1]:
            if p not in curr or not isinstance(curr[p], dict):
                curr[p] = {}
            curr = curr[p]
        curr[parts[-1]] = val

    # 1. Global / backend settings
    for key, val in flatten_dict(global_config):
        if backend_name == "sim" and ("channel." in key or "shm." in key or "file." in key):
            continue  # Let SimBackend use default /tmp/proxy_sim sockets in simulation mode
        _set_path(result, key, val)

    # 2. Telemetry and simulation identifiers
    handler_name = handler_spec.get("name")
    if handler_name:
        global_prefix = (
            global_config.get("telemetry", {}).get("prefix", "proxy")
            if isinstance(global_config.get("telemetry"), dict)
            else global_config.get("telemetry.prefix", "proxy")
        )
        _set_path(result, "telemetry.prefix", f"{global_prefix}.{handler_name}")
        _set_path(result, "sim.handler_name", handler_name)

    if backend_name == "sim":
        _set_path(result, "sim.event_sock", "/tmp/proxy_sim_events.sock")

    # 3. Standard channel routing aliases
    if "input_channel" in handler_spec:
        in_ch = handler_spec["input_channel"]
        for prefix in ("channel.input", "egress.input_channel", "dummy.channel", "print.channel",
                       "split.input_channel", "scatter.input_channel", "xml.input_channel",
                       "order.input_channel", "route.input_channel"):
            _set_path(result, prefix, in_ch)

    if "input_channels" in handler_spec:
        in_chs = handler_spec["input_channels"]
        val_chs = in_chs if isinstance(in_chs, list) else [s.strip() for s in str(in_chs).split(",") if s.strip()]
        _set_path(result, "merge.input_channels", ",".join(val_chs) if isinstance(in_chs, str) else in_chs)
        _set_path(result, "gather.input_channels", ",".join(val_chs) if isinstance(in_chs, str) else in_chs)

    if "output_channel" in handler_spec:
        out_ch = handler_spec["output_channel"]
        for prefix in ("channel.output", "ingress.output_channel", "dummy.channel", "merge.output_channel",
                       "gather.output_channel", "xml.output_channel", "order.output_channel"):
            _set_path(result, prefix, out_ch)
        default_action = handler_spec.get("config", {}).get("default_action")
        if default_action == "forward":
            _set_path(result, "route.default_output", out_ch)

    if "output_channels" in handler_spec:
        out_chs = handler_spec["output_channels"]
        val_chs = out_chs if isinstance(out_chs, list) else [s.strip() for s in str(out_chs).split(",") if s.strip()]
        _set_path(result, "split.output_channels", ",".join(val_chs) if isinstance(out_chs, str) else out_chs)
        _set_path(result, "scatter.output_channels", ",".join(val_chs) if isinstance(out_chs, str) else out_chs)

    # 4. Handler-specific parameter overrides
    params = handler_spec.get("config", {})

    # Route handler structured rules
    if handler_spec.get("type") == "route_handler" and "rules" in params and isinstance(params["rules"], list):
        # Directly pass the rules array
        _set_path(result, "route.rules", params["rules"])

    for key, val in params.items():
        if key == "rules" and handler_spec.get("type") == "route_handler":
            continue
        if isinstance(val, dict):
            for sub_k, sub_v in flatten_dict(val, prefix=key):
                _set_path(result, sub_k, sub_v)
        else:
            if backend_name == "sim" and key == "dummy.delay_ms":
                _set_path(result, key, 999999999)
            else:
                _set_path(result, key, val)

    if backend_name == "sim" and handler_spec.get("type") == "dummy_send" and "dummy.delay_ms" not in params:
        _set_path(result, "dummy.delay_ms", 999999999)

    return json.dumps(result, indent=2)

