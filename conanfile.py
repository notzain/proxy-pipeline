import os

from conan import ConanFile
from conan.tools.cmake import CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import save


class ProxyConan(ConanFile):
    name = "proxy"
    version = "0.1.0"
    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    options = {
        "backend_file": [True, False],
        "backend_socket": [True, False],
        "backend_uds": [True, False],
        "backend_shm": [True, False],
        "backend_sim": [True, False],
    }
    default_options = {
        "backend_file": True,
        "backend_socket": True,
        "backend_uds": True,
        "backend_shm": True,
        "backend_sim": True,
        "spdlog/*:header_only": True,
        "xerces-c/*:network": False,
        "xerces-c/*:transcoder": "iconv",
    }

    def layout(self):
        cmake_layout(self)

    def requirements(self):
        # Core third-party dependencies
        self.requires("spdlog/1.17.0")
        self.requires("fmt/12.1.0")
        self.requires("nlohmann_json/3.11.3")
        self.requires("pugixml/1.14")
        self.requires("libxml2/2.13.6")
        self.requires("xerces-c/3.3.0")
        self.requires("catch2/3.8.0")

        # Backends discovered / required via Conan
        if self.options.backend_file:
            self.requires("backend-file/0.1.0")
        if self.options.backend_socket:
            self.requires("backend-socket/0.1.0")
        if self.options.backend_uds:
            self.requires("backend-uds/0.1.0")
        if self.options.backend_shm:
            self.requires("backend-shm/0.1.0")
        if self.options.backend_sim:
            self.requires("backend-sim/0.1.0")

    def generate(self):
        deps = CMakeDeps(self)
        deps.generate()
        tc = CMakeToolchain(self)
        tc.generate()

        # Discover backends from Conan dependency graph
        backend_entries = []
        for req, dep in self.dependencies.items():
            is_backend = dep.cpp_info.get_property(
                "proxy_component"
            ) == "backend" or req.ref.name.startswith("backend-")
            if is_backend and req.ref.name != "backend-interface":
                short_name = dep.cpp_info.get_property(
                    "backend_name"
                ) or req.ref.name.removeprefix("backend-")
                target_name = f"{req.ref.name}::{req.ref.name}"
                backend_entries.append((target_name, short_name, req.ref.name))

        # Generate ConanBackends.cmake in the generators folder
        lines = [
            "#[=======================================================================[",
            "Auto-generated by Conan 2 ProxyConan.generate()",
            "Discovered backends from Conan dependency graph.",
            "#]=======================================================================]",
            "",
        ]
        for target, name, pkg_name in backend_entries:
            lines.append(f"# Discovered backend: {name} (package: {pkg_name})")
            lines.append(
                f'proxy_register_conan_backend("{name}" "{target}" "{pkg_name}")'
            )
            lines.append("")

        save(
            self,
            os.path.join(self.generators_folder, "ConanBackends.cmake"),
            "\n".join(lines),
        )
